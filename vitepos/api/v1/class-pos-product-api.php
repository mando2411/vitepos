						$this->get_outlet_id(),
						$this->get_current_user_id(),
						$quantity,
						! empty( $vari['id'] )
					) ) {

						$this->add_error( 'Stock add is not possible' );
						$this->set_response( false, '', null );

						return $this->response->get_response();
					}
				} else {
					$variation->set_stock_quantity( $quantity );
					if ( $variation->get_stock_quantity() > 0 ) {
						$variation->set_stock_status( 'instock' );
					}
					$variation->save();
				}
			} else {
				$variation->set_manage_stock( false );
				$variation->save();
			}
			POS_Product::set_purchase_cost( $variation_id, $vari['purchase_cost'] );
		}

		return $variation;
	}

	/**
	 * The set global uid is generated by appsbd
	 *
	 * @param mixed $unique_id It is unique_id param.
	 * @param \WC_Product_Simple|\WC_Product_Variation $product It is product param.
	 * @param bool $is_edit It is is_edit param.
	 *
	 * @return boolean
	 */
	public function set_global_uid( &$product, $unique_id, $is_edit = false ) {
		if ( method_exists( $product, 'get_global_unique_id' ) ) {
			if ( ! $is_edit || ( $product->get_global_unique_id() != $unique_id ) ) {
				$global_unique_id_found = wc_get_product_id_by_global_unique_id( $unique_id );
				if ( ! empty( $global_unique_id_found ) && $global_unique_id_found != $product->get_id() ) {
					return false;
				}
				$product->set_global_unique_id( $unique_id );
			}
		}

		return true;
	}

