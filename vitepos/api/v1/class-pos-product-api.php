			$appdb->prefix . 'woocommerce_attribute_taxonomies',
			array( 'attribute_label' => sanitize_text_field( $attr_label ) ),
			array( 'attribute_id' => (int) $attribute_id ),
			array( '%s' ),
			array( '%d' )
		);

		if ( $updated === false ) {
			$this->add_error( 'Failed to update attribute label' );
			$this->response->set_response( false, '' );

			return $this->response;
		}

		delete_transient( 'wc_attribute_taxonomies' );
		wc_delete_product_transients();

		$terms_data = $this->get_payload( 'terms', array() );
		if ( ! empty( $terms_data ) ) {
			$taxonomy = wc_attribute_taxonomy_name( $attribute->attribute_name );

			$existing_terms = get_terms(
				array(
					'taxonomy'   => $taxonomy,
					'hide_empty' => false,
