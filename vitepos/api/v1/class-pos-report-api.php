	/**
	 * The scan product is generated by appsbd
	 *
	 * @return \Appsbd\V1\libs\API_Response
	 */
	public function product_details() {
		$report     = new Vitepos_Report_Data();
		$product_id = $this->get_payload( 'id', '' );
		$stock_type = POS_Settings::is_default_stock() ? '_stock' : '_vt_stocks';
		if ( ! empty( $product_id ) ) {
			$product_info               = new \stdClass();
			$product_info->product_data = $report->search_product( $product_id );
			$product_info->img_url      = $this->get_product_img_url( $product_id, 'full' );
			$product_stock              = ViteposModel::get_db_object()->get_results( "SELECT meta_value as stock FROM {$this->postmeta} WHERE {$this->postmeta}.post_id = {$product_id} AND {$this->postmeta}.meta_key = '{$stock_type}';" );

			if ( POS_Settings::is_default_stock() ) {
				$product_info->stock_data = $product_stock ? appsbd_wc_amount( $product_stock[0]->stock ) : 0;
			} elseif ( ! empty( $product_stock ) && isset( $product_stock[0]->stock ) ) {
				$product_info->stock_data = unserialize( $product_stock[0]->stock );
			} else {
				$product_info->stock_data = array();
			}
			$outlets       = Mapbd_pos_warehouse::get_outlet_details( null, true );
			$product_assoc = array();
			foreach ( $product_info->product_data as $product ) {
				$product_assoc[ $product->outlet_id ] = $product;
			}
			foreach ( $outlets as $outlet ) {
				if ( ! isset( $product_assoc[ $outlet->id ] ) ) {
					$product_assoc[ $outlet->id ] = array(
						'outlet_id'         => $outlet->id,
						'total_ordered_qty' => 0,
					);
				}
			}
			$product_info->product_data = $product_assoc;
			if ( ! empty( $product_info ) ) {
				$this->response->set_response( true, 'Product found', $product_info );
			} else {
				$this->response->set_response( false, 'No product Found', array() );
			}

			return $this->response;
		} else {
			$this->response->set_response( false, 'Invalid Id', array() );
		}

		return $this->response;
	}


