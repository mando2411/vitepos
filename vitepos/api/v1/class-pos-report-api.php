	/**
	 * The set route permission is generated by appsbd
	 *
	 * @param \VitePos\Libs\any $route Its string.
	 *
	 * @return bool|void
	 */
	public function set_route_permission( $route ) {
		if ( "dashboard-report == $route" ) {
			return current_user_can( 'report-menu' );
		} elseif ( "order-report == $route" ) {
			return current_user_can( 'report-order' );
		} elseif ( 'product-report' == $route ) {
			return current_user_can( 'report-product' );
		} elseif ( 'customer-report' == $route ) {
			return current_user_can( 'report-customer' );
		} else {
			return current_user_can( 'report-staff' );
		}

		return parent::set_route_permission( $route );
	}

	/**
	 * The order report is generated by appsbd
	 *
	 * @return \Appsbd\V1\libs\API_Response
	 */
	public function order_report() {
		$response_data = new API_Data_Response();
		$args          = array(
			'status'        => array( POS_Settings::def_oder_status(), 'completed' ),
			'limit'         => $this->get_payload( 'limit', 20 ),
			'page'          => $this->get_payload( 'page', 1 ),
			'orderby'       => 'date',
			'order'         => 'DESC',
			'paginate'      => true,
			'vt_meta_query' => array(
				array(
					'key'     => '_is_vitepos',
					'value'   => 'Y',
					'compare' => '=',
				),
			),
		);
		if ( ! POS_Settings::is_admin_user() && ! current_user_can( 'can-refund-any-order' ) ) {
			$outlets = get_user_meta( $this->get_current_user_id(), 'outlet_id', true );
			if ( is_array( $outlets ) ) {
				$args['vt_meta_query'][] = array(
					'key'     => '_vtp_outlet_id',
					'value'   => $outlets,
					'compare' => 'IN',
				);
			} else {
				$this->add_error( "You don't have permission to view details of this outlet" );
				$response_data->set_total_records( 0 );
				$this->response->set_response( false, '', $response_data );

				return $this->response->get_response();
			}
		}
		$src_props     = $this->get_payload( 'src_by', array() );
		$sort_by_props = $this->get_payload( 'sort_by', array() );
		POS_Order::order_search_props( $args, $src_props );
		POS_Order::order_sort_param( $sort_by_props, $args );

		$orders = wc_get_orders( $args );

		$orderlist = array();
		if ( ! empty( $orders->orders ) && is_array( $orders->orders ) ) {
			foreach ( $orders->orders as $order ) {
				$order_data  = POS_Order::get_from_woo_order( $order );
				$orderlist[] = $order_data;
			}
		}

		$page                 = $this->get_payload( 'page', 1 );
		$limit                = $this->get_payload( 'limit', 20 );
		$response_data->page  = $page;
		$response_data->limit = $limit;
		$type                 = $this->get_payload( 'request_type', '' );
		if ( ! empty( $type ) && 'pdf' == $type ) {
			if ( ! empty( $orders->total ) ) {
				$limit                = $this->set_limit( $orders->total );
				$response_data->limit = $limit;
			}
		}

		if ( $response_data->set_total_records( $orders->total ) ) {
			$response_data->rowdata = $orderlist;
		}

		$this->response->set_response( true, 'Order found', $response_data );

		return $this->response;
	}

	/**
	 * The product report is generated by appsbd
	 *
	 * @return API_Data_Response
	 */
	public function product_report() {
		$response_data = new API_Data_Response();
		$report        = new Vitepos_Report_Data();
		$src_props     = $this->get_payload( 'src_by', array() );
		$sort_by_props = $this->get_payload( 'sort_by', array() );

		$start_date = null;
		$end_date   = null;
		$outlet_id  = null;
		foreach ( $src_props as $item ) {
			if ( isset( $item['prop'] ) && 'outlet_id' === $item['prop'] ) {
				$outlet_id = $item['val'];
			}
			if ( isset( $item['prop'] ) && 'order_date' === $item['prop'] ) {
				if ( is_array( $item['val'] ) ) {
					$start_date = $item['val']['start'];
					$end_date   = $item['val']['end'];
				} else {
					$start_date = $item['val'];
					$end_date   = $item['val'];
				}
			}
		}
		if ( empty( $outlet_id ) ) {
			$outlet_id = $this->get_outlet_id();
		}

		if ( $this->is_hpos() ) {
			$total_product = ViteposModel::get_db_object()->get_results(
				"
		SELECT COUNT(*) AS total_records
		FROM (
    		SELECT 
        		{$this->posts}.ID AS counted_product_id,
        		{$this->posts}.post_type
    		FROM {$this->posts}
   			WHERE {$this->posts}.post_type IN ('product', 'product_variation') 
      			AND {$this->posts}.post_status IN  ('publish','private')
    		GROUP BY 
        		{$this->posts}.ID
			) AS product_counts
		WHERE 
    		(post_type = 'product' 
    			AND NOT EXISTS (
        		SELECT 1 
        			FROM {$this->posts} AS variations 
       				WHERE variations.post_parent = product_counts.counted_product_id 
        				AND variations.post_type = 'product_variation'
    			)
    		) 
    	OR post_type = 'product_variation';
		"
			);
		} else {
			$total_product = ViteposModel::get_db_object()->get_results(
				"
			SELECT COUNT(*) AS total_records
			FROM (
                SELECT 
                    {$this->posts}.ID AS counted_product_id,
                    {$this->posts}.post_type
                FROM {$this->posts}
                LEFT JOIN {$this->posts} AS variations ON variations.post_parent = {$this->posts}.ID 
                    AND variations.post_type = 'product_variation'
                WHERE {$this->posts}.post_type IN ('product', 'product_variation') 
                    AND {$this->posts}.post_status IN  ('publish','private')
                GROUP BY {$this->posts}.ID
                HAVING ({$this->posts}.post_type = 'product' AND COUNT(variations.ID) = 0)
                    OR {$this->posts}.post_type = 'product_variation'
			) AS product_counts;"
			);
		}

		$page                 = $this->get_payload( 'page', 1 );
		$limit                = $this->get_payload( 'limit', 20 );
		$response_data->page  = $page;
		$response_data->limit = $limit;

		$product_list = $report->product_list( $outlet_id, $start_date, $end_date, $limit, $page );
		foreach ( $product_list as &$product ) {
			if ( ! empty( $product->product_id ) ) {
				$product->image_url = $this->get_product_img_url( $product->product_id, 'full' );
			}
		}
		if ( $response_data->set_total_records( $total_product[0]->total_records ) ) {
			$response_data->rowdata = $product_list;
		}

		return $response_data;
	}

