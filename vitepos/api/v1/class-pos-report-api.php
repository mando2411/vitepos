	/**
	 * The customer report is generated by appsbd
	 */
	public function customer_report() {
		$response_data = new API_Data_Response();
		$report        = new Vitepos_Report_Data();

		$src_props     = $this->get_payload( 'src_by', array() );
		$sort_by_props = $this->get_payload( 'sort_by', array() );

		$outlet_id       = null;
		$name            = null;
		$email           = null;
		$name_condition  = '';
		$email_condition = '';

		foreach ( $src_props as $item ) {
			if ( isset( $item['prop'] ) && 'outlet_id' === $item['prop'] ) {
				$outlet_id = $item['val'];
			}
			if ( isset( $item['prop'] ) && 'name' === $item['prop'] ) {
				$name           = trim( $item['val'], " \n\r\t\v\0" );
				$name_condition = "AND ({$this->users}.display_name LIKE '$name' OR {$this->users}.user_login LIKE '$name' OR fn.meta_value LIKE '$name' OR ln.meta_value Like '$name')";
			}
			if ( isset( $item['prop'] ) && 'email' === $item['prop'] ) {
				$email           = trim( $item['val'], " \n\r\t\v\0" );
				$email_condition = "AND {$this->users}.user_email = '$email'";
			}
		}

		if ( empty( $outlet_id ) ) {
			$outlet_id = $this->get_outlet_id();
		}
		if ( $this->is_hpos() ) {
			$total_customer = ViteposModel::get_db_object()->get_results(
				"
			SELECT
				COUNT(DISTINCT {$this->users}.ID) AS user_count 
				FROM {$this->wc_orders}
				INNER JOIN {$this->users} ON {$this->wc_orders}.customer_id = {$this->users}.ID 	
				INNER JOIN {$this->wc_orders_meta} AS ot ON {$this->wc_orders}.id = ot.order_id 
					AND ot.meta_key = '_vtp_outlet_id' 
					AND ot.meta_value = {$outlet_id}
				LEFT JOIN {$this->usermeta} AS fn ON {$this->users}.ID = fn.user_id 
                     AND fn.meta_key = 'first_name'
                LEFT JOIN {$this->usermeta} AS ln ON {$this->users}.ID = ln.user_id 
                    AND ln.meta_key = 'last_name'	
	
				WHERE 1=1
				{$name_condition}
				{$email_condition}"
			);
		} else {
			$total_customer = ViteposModel::get_db_object()->get_results(
				"
			SELECT
                COUNT(DISTINCT u.id) AS user_count
				FROM {$this->posts}
				INNER JOIN {$this->postmeta} AS ot ON {$this->posts}.ID = ot.post_id 
                    AND ot.meta_key = '_vtp_outlet_id' 
                    AND ot.meta_value = {$outlet_id}
				INNER JOIN {$this->postmeta} AS um ON {$this->posts}.ID = um.post_id 
                    AND um.meta_key = '_customer_user'
				INNER JOIN {$this->users} AS u ON um.meta_value = u.ID
				LEFT JOIN {$this->usermeta} AS fn ON u.ID = fn.user_id 
                    AND fn.meta_key = 'first_name'
                LEFT JOIN {$this->usermeta} AS ln ON u.ID = ln.user_id 
                    AND ln.meta_key = 'last_name'
				WHERE 1=1
				{$name_condition}
				{$email_condition}"
			);
		}

		$page                 = $this->get_payload( 'page', 1 );
		$limit                = $this->get_payload( 'limit', 20 );
		$response_data->page  = $page;
		$response_data->limit = $limit;
		$type                 = $this->get_payload( 'request_type', '' );
		if ( ! empty( $type ) && 'pdf' == $type ) {
			if ( ! empty( $total_customer[0]->user_count ) ) {
				$limit                = $this->set_limit( $total_customer[0]->user_count );
				$response_data->limit = $limit;
			}
		}

		$customer_data = $report->top_customers( $outlet_id, null, null, $name, $email, $limit, $page );

		if ( $response_data->set_total_records( $total_customer[0]->user_count ) ) {
			$response_data->rowdata = $customer_data;
		}

		return $response_data;
	}

