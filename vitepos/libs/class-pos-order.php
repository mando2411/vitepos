	/**
	 * The add time by status is generated by appsbd
	 *
	 * @param any $order its order param.
	 * @param any $status its status param.
	 *
	 * @return bool
	 */
	public static function add_time_by_status( $order, $status ) {
		$time_meta_key = '_vt_time_log';
		$time_logs     = $order->get_meta( $time_meta_key );
		if ( ! is_array( $time_logs ) ) {
			$time_logs = array();
		}
		$time_obj         = new \stdClass();
		$time_obj->status = $status;
		$time_obj->time   = gmdate( 'Y-m-d H:i:s' );
		$time_logs[]      = $time_obj;
		if ( vitepos_wc_update_meta( $order->get_id(), $time_meta_key, $time_logs ) ) {
			return true;
		}
		return false;
	}

	/**
	 * The pick user app order is generated by appsbd
	 *
	 * @param mixed $order_id It is order_id param.
	 * @param mixed $waiter_id It is waiter_id param.
	 *
	 * @return \stdClass|void
	 */
	public static function pick_user_app_order( $order_id, $waiter_id ) {
		$order = wc_get_order( $order_id );
		
		$assign_statuses = array( 'vtu_order_placed', 'vtu_order_picked', 'pending', 'processing', 'on-hold' );
		$order->update_meta_data( '_vtp_order_by', $waiter_id ); 

		$waiter      = get_user( $waiter_id );
		$waiter_name = appsbd_get_user_title_by_user( $waiter );
		if ( get_current_user_id() == $waiter_id ) {
			$msg = 'Order picked by ' . $waiter_name;
		} else {
			$msg = 'Order assigned to ' . $waiter_name;
		}
		if ( in_array( $order->get_status(), $assign_statuses ) ) {
			if ( $order->update_status( 'vtu_order_picked', $msg, true ) ) {
				self::add_time_by_status( $order, 'vtu_order_picked' );
				self::add_resto_order_msg( $order_id, $msg, $waiter );
				$order->save();
				if ( $order->get_meta( '_vtp_is_item_wise' ) == 'Y' ) {
					$items = $order->get_items();
					foreach ( $items as $oitem ) {
						$oitem->update_meta_data( '_vtp_item_status', 'vt_it_picked' );
						$oitem->update_meta_data( '_vtp_item_can_cancel', 'Y' );
						$oitem->save();
					}
				}
				POS_Settings::get_module_instance()->add_info( 'Order successfully picked' );
				$order_details = self::get_from_woo_order_restro_by_id(
					$order_id,
					false,
					true
				);
				return $order_details;
			}
		} else {
				self::add_resto_order_msg( $order_id, $msg, $waiter );
				$order->save();
				POS_Settings::get_module_instance()->add_info( 'Order successfully picked' );
				$order_details = self::get_from_woo_order_restro_by_id(
					$order_id,
					false,
					true
				);
				return $order_details;
		}
	}
