	/**
	 * The calculate refund fee discount is generated by appsbd
	 *
	 * @param mixed     $total_fees It is total_fees param.
	 * @param mixed     $total_discount It is total_discount param.
	 * @param mixed     $v_order It is v_order param.
	 * @param \WC_Order $order It is order param.
	 */
	public static function calculate_refund_fee_discount( &$total_fees, &$total_discount, $v_order, $order ) {
		$total_fees = 0.0;
		$total_discount = 0.0;

		$include_tax = $order->get_prices_include_tax();
		if ( $include_tax && $order->meta_exists( '_vt_sub_total' ) ) {
			$order_total = $order->get_meta( '_vt_sub_total' ); 
		} else {
			$order_total = $order->get_subtotal(); 
		}

		foreach ( $v_order->discounts as $discount ) {

			if ( $discount->type == 'P' ) {
				$total_discount += ( $order_total * ( doubleval( $discount->val ) / 100 ) );
			} else {
				$total_discount += doubleval( $discount->val );
			}
		}
		if ( ! empty( $v_order->c_discounts ) ) {
			foreach ( $v_order->c_discounts as $discount ) {

				if ( $discount->type == 'P' ) {
					$total_discount += ( $order_total * ( doubleval( $discount->val ) / 100 ) );
				} else {
					$total_discount += doubleval( $discount->val );
				}
			}
		}

		foreach ( $v_order->fees as $item ) {
			if ( $item->type == 'P' ) {
				$total_fees += ( $order_total * ( doubleval( $item->val ) / 100 ) );
			} else {
				$total_fees += doubleval( $item->val );
			}
		}
		if ( ! empty( $v_order->c_fees ) ) {
			foreach ( $v_order->c_fees as $item ) {
				if ( $item->type == 'P' ) {
					$total_fees += ( $order_total * ( doubleval( $item->val ) / 100 ) );
				} else {
					$total_fees += doubleval( $item->val );
				}
			}
		}
		$total_fees = vitepos_wc_amount( $total_fees );
		$total_discount = vitepos_wc_amount( $total_discount );
	}
