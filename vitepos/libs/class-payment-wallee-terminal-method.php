	/**
	 * The initialize is generated by appsbd
	 *
	 * @return mixed|void
	 */
	public function initialize() {
		$this->set_admin_name( 'wallee_terminal' );
		$this->title = 'Wallee Terminal';
		$this->icon  = 'vps vps-wallee-w-icon';
		$this->id    = 'L';
		$this->comp  = 'basic';
		$this->allow_kiosk = true;
		$this->set_next_handler( 'WTP', 'WalleeTerminal' );
		add_filter( 'vitepos/filter/header-links', array( $this, 'prefetch_script' ), 11 );
		add_filter( 'vitepos/filter/footer-scripts', array( $this, 'footer_script' ), 9 );
